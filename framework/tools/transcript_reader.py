"""Transcript Reader Tool — return Whisper-transcribed speech with timestamps.

Reads a pre-computed .srt file (one per video) generated by Whisper large-v3.
Agent receives time-aligned dialogue that may not be fully captured by the
visual analyzer. Useful when speech content drives the answer.
"""
import logging
import re
from pathlib import Path
from typing import List, Optional

from .base import BaseTool, ToolParameter, ToolResult

logger = logging.getLogger(__name__)

SRT_RE = re.compile(
    r"(\d+)\s+(\d{2}:\d{2}:\d{2},\d{3})\s*-->\s*(\d{2}:\d{2}:\d{2},\d{3})\s+(.*?)(?=\n\n|\Z)",
    re.DOTALL,
)


def _srt_ts_to_seconds(ts: str) -> float:
    hh, mm, rest = ts.split(":")
    ss, ms = rest.split(",")
    return int(hh) * 3600 + int(mm) * 60 + int(ss) + int(ms) / 1000.0


def parse_srt(srt_path: Path) -> List[dict]:
    if not srt_path.exists():
        return []
    text = srt_path.read_text(encoding="utf-8")
    if not text.strip():
        return []
    segs = []
    for m in SRT_RE.finditer(text):
        segs.append({
            "start": _srt_ts_to_seconds(m.group(2)),
            "end": _srt_ts_to_seconds(m.group(3)),
            "text": m.group(4).replace("\n", " ").strip(),
        })
    return segs


class GetTranscriptTool(BaseTool):

    def __init__(self, srt_path: str, qid: Optional[int] = None):
        self._srt_path = Path(srt_path)
        self._qid = qid
        self._segments: Optional[List[dict]] = None

    def _load(self) -> List[dict]:
        if self._segments is None:
            self._segments = parse_srt(self._srt_path)
        return self._segments

    @property
    def name(self) -> str:
        return "get_transcript"

    @property
    def description(self) -> str:
        return (
            "Return the spoken-dialogue transcript for this video, as a list of "
            "time-aligned segments {start, end, text}. Optionally filter by time range. "
            "Transcripts are produced by Whisper large-v3 on the video's audio track. "
            "Returns an empty list if the video has no speech (e.g., music-only). "
            "Use when speech content (words said, who speaks, order of statements, "
            "named entities, counts of utterances) might be relevant to the answer."
        )

    @property
    def parameters(self) -> List[ToolParameter]:
        return [
            ToolParameter(
                name="start_time",
                type="number",
                description="Start of filter window in seconds. Omit to return from 0.",
                required=False,
                default=None,
            ),
            ToolParameter(
                name="end_time",
                type="number",
                description="End of filter window in seconds. Omit to return to end.",
                required=False,
                default=None,
            ),
        ]

    async def execute(
        self,
        start_time: Optional[float] = None,
        end_time: Optional[float] = None,
        **kwargs,
    ) -> ToolResult:
        segments = self._load()
        if not segments:
            return ToolResult(
                success=True,
                data={
                    "qid": self._qid,
                    "segment_count": 0,
                    "segments": [],
                    "note": "No speech detected in this video (music-only or ambient audio).",
                },
                metadata={"srt_path": str(self._srt_path)},
            )

        # Filter by time range (overlap semantics)
        filtered = [
            s for s in segments
            if (start_time is None or s["end"] > start_time)
            and (end_time is None or s["start"] < end_time)
        ]
        return ToolResult(
            success=True,
            data={
                "qid": self._qid,
                "window": {"start_time": start_time, "end_time": end_time},
                "segment_count": len(filtered),
                "segments": filtered,
            },
            metadata={"srt_path": str(self._srt_path), "total_segments": len(segments)},
        )
